/** @file ToolChainHarnessLib.c
    HBFAplus Toolchain Harness Library - Main entry point for AFL++ fuzzing.

    This library provides the main() entry point for fuzzing harnesses.
    It handles:
    - One-time initialization via InitializeHarness()
    - Per-iteration setup (buffer, timer reset)
    - Cleanup registration via atexit()

    Architecture:
    1. main() is called by AFL++ (each forked child runs once)
    2. First call triggers InitializeHarness() and registers CleanupHarness()
    3. Each iteration: reset timer, set fuzz buffer, call RunTestHarness()
    4. On exit: CleanupHarness() is called via atexit()

    Harness Contract:
    - Harness MUST implement: InitializeHarness(), CleanupHarness(),
      RunTestHarness(), GetMaxBufferSize()
    - InitializeHarness: One-time setup (allocate persistent structures)
    - CleanupHarness: Free persistent allocations
    - RunTestHarness: Per-iteration test execution
    - GetMaxBufferSize: Return max fuzz input size

    Based on HBFA's original ToolChainHarnessLib.c with HBFAplus extensions.

    Copyright (c) 2019, Intel Corporation. All rights reserved.
    Copyright (c) 2024, HBFAplus Contributors. All rights reserved.
    SPDX-License-Identifier: BSD-2-Clause-Patent
**/

