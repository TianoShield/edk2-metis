/**
  Main entry point for AFL++ fuzzing.

  AFL passes input via a file specified on the command line.
  In standard AFL mode (no __AFL_INIT / __AFL_LOOP), the fork server
  sits at the first instrumented basic block.  Every forked child
  starts fresh from here, so each process runs once and exits.

  Flow:
  1. Read fuzz input from file
  2. Initialize fuzz context pool and load bytes
  3. Call library constructors and harness init
  4. Run test
  5. Cleanup via atexit

  @param[in]  argc  Argument count
  @param[in]  argv  Argument vector (argv[1] = input file)

  @return  0 on success, non-zero on error
**/
int
main (
  int   argc,
  char  **argv
  )
{
  VOID   *TestBuffer;
  UINTN  TestBufferSize;
  UINTN  BootstrapSize;

  //
  // 1. Read fuzz input from file into buffer.
  //
  InitTestBuffer (argc, argv, GetMaxBufferSize (), &TestBuffer, &TestBufferSize);

  //
  // 2. Acquire pool and load fuzz bytes BEFORE constructors —
  //    mock constructors consume from the pool.
  //
  //    In standard AFL mode (no __AFL_INIT / __AFL_LOOP), the fork server
  //    sits at the first instrumented basic block.  Every forked child
  //    starts fresh from here, so there is no "subsequent iteration" —
  //    each process runs once and exits.
  //
  gFuzzCtx = MockFuzzContextGetPool ();
  MockFuzzContextInit (gFuzzCtx, (UINT8 *)TestBuffer, TestBufferSize);

  //
  // 3. Bootstrap region setup.
  //    If the harness declares a bootstrap size, set a soft limit so
  //    that constructors and InitializeHarness can only consume bytes
  //    within the bootstrap region.  This makes the seed layout
  //    deterministic: [ bootstrap | harness payload ].
  //
  BootstrapSize = GetBootstrapSize ();
  if (BootstrapSize > 0) {
    DEBUG ((DEBUG_INFO, "HBFAplus: Bootstrap region = %u bytes\n", (UINT32)BootstrapSize));
    MockFuzzContextSetLimit (gFuzzCtx, BootstrapSize);
  }

  //
  // 4. Pre-constructor environment setup.
  //    MockTimerInit: one-time init — marks timer active, registers
  //    TimerAdvanceFn on the pool so AdvanceTime can advance time.
  //    MockEventResetState: per-iteration reset — clears events,
  //    close listeners, simulated time, and firing guard.
  //    MockEventSetAdvanceContext: sets the advance context so that
  //    MockFuzzContextAdvanceTime can signal registered events.
  //
  MockTimerInit ();
  MockEventResetState ();
  MockEventSetAdvanceContext (gFuzzCtx);

  //
  // 5. Call library constructors.
  //    In native UEFI the DXE dispatcher does this automatically.
  //    In HBFAplus (rehosted to userspace Linux) we do it manually.
  //
  DEBUG ((DEBUG_INFO, "HBFAplus: Calling ProcessLibraryConstructorList\n"));
  ProcessLibraryConstructorList ();

  //
  // 6. Harness-specific one-time init.
  //
  DEBUG ((DEBUG_INFO, "HBFAplus: Running InitializeHarness\n"));
  InitializeHarness ();
  atexit (CleanupHarnessWrapper);

  //
  // 7. End bootstrap region.
  //    Clear the limit so RunTestHarness has access to the full remaining
  //    buffer.  Advance the offset to exactly BootstrapSize so the harness
  //    payload starts at a fixed, seed-friendly position regardless of how
  //    many bootstrap bytes were actually consumed.
  //
  if (BootstrapSize > 0) {
    DEBUG ((DEBUG_INFO, "HBFAplus: Bootstrap consumed %u / %u bytes\n",
            (UINT32)gFuzzCtx->Offset, (UINT32)BootstrapSize));
    MockFuzzContextClearLimit (gFuzzCtx);
    MockFuzzContextAdvanceTo (gFuzzCtx, BootstrapSize);
  }

  //
  // 8. Run harness, cleanup.
  //
  RunTestHarness (gFuzzCtx);
  MockFuzzContextReset (gFuzzCtx);

  //
  // Note: TestBuffer is intentionally NOT freed here.  CleanupHarness
  // (registered via atexit) may trigger driver disconnect paths that
  // issue protocol commands reading from the fuzz buffer.  Freeing
  // the buffer before atexit runs causes a use-after-free.  The OS
  // reclaims all heap memory on process exit.
  //

  return 0;
}

